class TestHelpers:
    @pytest.mark.parametrize(
        ("name", "kind"),
        [("Part.GCODE.3MF", "gcode.3mf"), ("model.3mf", "3mf"), ("photo.JPG", "jpg"), ("README", "unknown")],
    )
    def test_classify_file_type(self, name, kind):
        assert library.classify_file_type(name) == kind

    def test_paths_are_kept_inside_the_data_directory(self, storage):
        assert library.to_absolute_path(None) is None
        assert library.to_absolute_path("library/a.3mf") == (storage / "library/a.3mf").resolve()
        assert library.to_relative_path(storage / "library/a.3mf") == "library/a.3mf"
        assert library.to_relative_path("/elsewhere/a.3mf") == "/elsewhere/a.3mf"
        assert library.to_relative_path("") == ""
        with pytest.raises(ValueError):
            library.to_absolute_path("../../etc/passwd")

    @pytest.mark.parametrize(
        ("name", "content", "message"),
        [
            ("part.gcode", b"G28", "Raw .gcode files can't be printed"),
            ("part.gcode.3mf", b"G28 renamed", "isn't a valid ZIP container"),
        ],
    )
    def test_rejects_unprintable_uploads(self, name, content, message):
        with pytest.raises(HTTPException) as exc:
            library.validate_print_file_upload(name, content)
        assert message in exc.value.detail

    def test_accepts_printable_and_other_files(self):
        library.validate_print_file_upload("part.gcode.3mf", b"PK\x03\x04rest")
        library.validate_print_file_upload("part.stl", b"solid")


class TestGcodeThumbnail:
    def test_extracts_embedded_thumbnail(self, tmp_path):
        path = tmp_path / "part.gcode"
        path.write_text(_gcode_with_thumbnails((96, b"thumbnail-bytes")))

        assert library.extract_gcode_thumbnail(path) == b"thumbnail-bytes"

    def test_no_thumbnail_or_bad_data(self, tmp_path):
        plain = tmp_path / "plain.gcode"
        plain.write_text("G28\nG1 X1\n")
        broken = tmp_path / "broken.gcode"
        broken.write_text("; thumbnail begin 32x32 4\n; @@@@\n; thumbnail end\n")

        assert library.extract_gcode_thumbnail(plain) is None
        assert not library.extract_gcode_thumbnail(broken)
        assert library.extract_gcode_thumbnail(tmp_path / "missing.gcode") is None

    def test_prefers_the_largest_thumbnail_up_to_300px(self, tmp_path):
        path = tmp_path / "multi.gcode"
        path.write_text(_gcode_with_thumbnails((300, b"large"), (48, b"icon")))

        assert library.extract_gcode_thumbnail(path) == b"large"


class TestImageThumbnail:
    @pytest.mark.parametrize("mode", ["RGBA", "P", "L", "RGB"])
    def test_converts_to_rgb_png(self, tmp_path, mode):
        source = tmp_path / f"in-{mode}.png"
        color = (10, 20, 30, 128) if mode == "RGBA" else (40 if mode == "L" else (10, 20, 30))
        Image.new(mode, (20, 20), color if mode != "P" else 3).save(source)

        thumb = library.create_image_thumbnail(source, tmp_path)

        with Image.open(thumb) as img:
            assert (img.mode, img.size) == ("RGB", (20, 20))

    def test_shrinks_large_images(self, tmp_path):
        source = tmp_path / "big.png"
        source.write_bytes(_png((1024, 512)))

        with Image.open(library.create_image_thumbnail(source, tmp_path, max_size=256)) as img:
            assert img.size == (256, 128)

    def test_unreadable_image(self, tmp_path):
        source = tmp_path / "fake.png"
        source.write_bytes(b"not an image")

        assert library.create_image_thumbnail(source, tmp_path) is None


class TestUpload:
    async def _upload(self, client, name, content, **params):
        return await client.post("/api/v1/library/files/", files={"file": (name, content)}, params=params)

    async def test_sliced_3mf_gets_metadata_and_thumbnail(self, async_client: AsyncClient, storage):
        content = _zip(
            {
                "Metadata/plate_1.gcode": "G28",
                "Metadata/plate_1.png": _png(),
                "Metadata/slice_info.config": '<config><plate><metadata key="prediction" value="900"/></plate></config>',
            }
        )

        body = (await self._upload(async_client, "Part.gcode.3mf", content)).json()

        assert body["file_type"] == "gcode.3mf"
        assert body["thumbnail_path"].startswith("archive/library/thumbnails/")
        assert (storage / body["thumbnail_path"]).is_file()
        assert body["duplicate_of"] is None

    async def test_second_identical_upload_is_flagged_as_duplicate(self, async_client: AsyncClient, storage):
        first = (await self._upload(async_client, "a.png", _png())).json()
        second = (await self._upload(async_client, "b.png", _png())).json()

        assert second["duplicate_of"] == first["id"]
        assert second["thumbnail_path"]

    async def test_raw_gcode_is_rejected(self, async_client: AsyncClient, storage):
        response = await self._upload(async_client, "part.gcode", _gcode_with_thumbnails((96, b"t")))

        assert response.status_code == 400
        assert "Raw .gcode files" in response.json()["detail"]

    async def test_temporary_upload_goes_to_temporary_files(self, async_client: AsyncClient, storage, db_session):
        from backend.app.models.library import LibraryFile, LibraryFolder

        body = (await self._upload(async_client, "part.stl", b"solid x\nendsolid x\n", temporary="true")).json()

        row = await db_session.get(LibraryFile, body["id"])
        folder = await db_session.get(LibraryFolder, row.folder_id)
        assert folder.system_key is not None

    @pytest.mark.parametrize(
        ("params", "status"),
        [({"temporary": "true", "folder_id": 1}, 400), ({"folder_id": 9999}, 404)],
    )
    async def test_folder_errors(self, async_client: AsyncClient, storage, params, status):
        response = await self._upload(async_client, "part.stl", b"solid", **params)
        assert response.status_code == status


class TestZipExtract:
    async def _extract(self, client, content, name="bundle.zip", **params):
        return await client.post("/api/v1/library/files/extract-zip", files={"file": (name, content)}, params=params)

    async def test_recreates_folder_structure(self, async_client: AsyncClient, storage):
        content = _zip(
            {
                "Brackets/left.stl": "solid left\nendsolid left\n",
                "Brackets/Sub/right.png": _png(),
                "readme.txt": "hello",
                "__MACOSX/._junk": "x",
                "Brackets/": "",
            }
        )

        body = (await self._extract(async_client, content)).json()

        assert body["errors"] == []
        assert body["folders_created"] == 2
        assert sorted(f["filename"] for f in body["files"]) == ["left.stl", "readme.txt", "right.png"]
        folder_ids = {f["filename"]: f["folder_id"] for f in body["files"]}
        assert folder_ids["left.stl"] != folder_ids["right.png"]
        assert folder_ids["readme.txt"] is None

    async def test_flat_extraction_into_a_folder_named_after_the_zip(self, async_client: AsyncClient, storage):
        content = _zip({"a/one.stl": "solid\n", "b/two.stl": "solid\n"})

        body = (
            await self._extract(
                async_client, content, name="Kit.zip", preserve_structure="false", create_folder_from_zip="true"
            )
        ).json()

        assert body["folders_created"] == 1
        assert len({f["folder_id"] for f in body["files"]}) == 1

    async def test_sliced_and_gcode_files_inside_zip(self, async_client: AsyncClient, storage):
        sliced = _zip({"Metadata/plate_1.gcode": "G28", "Metadata/plate_1.png": _png()})
        content = _zip({"job.gcode.3mf": sliced, "raw.gcode": _gcode_with_thumbnails((64, b"gthumb"))})

        body = (await self._extract(async_client, content)).json()

        assert sorted(f["filename"] for f in body["files"]) == ["job.gcode.3mf", "raw.gcode"]

    @pytest.mark.parametrize(
        ("name", "content", "params", "status"),
        [
            ("notes.txt", b"x", {}, 400),
            ("broken.zip", b"not a zip", {}, 400),
            ("ok.zip", None, {"folder_id": 9999}, 404),
        ],
    )
    async def test_errors(self, async_client: AsyncClient, storage, name, content, params, status):
        payload = content if content is not None else _zip({"a.stl": "solid"})
        response = await self._extract(async_client, payload, name=name, **params)
        assert response.status_code == status
