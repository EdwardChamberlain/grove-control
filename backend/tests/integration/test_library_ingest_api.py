def _png(size=(40, 40), mode="RGB", color=(255, 0, 0)) -> bytes:
    buf = io.BytesIO()
    Image.new(mode, size, color).save(buf, "PNG")
    return buf.getvalue()


def _zip(files: dict[str, str | bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, data in files.items():
            zf.writestr(zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0)), data)
    return buf.getvalue()


def _gcode_with_thumbnails(*sizes: tuple[int, bytes]) -> str:
    lines = ["; generated by test"]
    for width, data in sizes:
        b64 = base64.b64encode(data).decode()
        lines.append(f"; thumbnail begin {width}x{width} {len(b64)}")
        lines.extend(f"; {b64[i : i + 60]}" for i in range(0, len(b64), 60))
        lines.append("; thumbnail end")
    lines.append("G28")
    return "\n".join(lines)


