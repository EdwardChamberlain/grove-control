"""Regression tests for G-code thumbnail selection."""

import base64

from backend.app.api.routes import library


def _gcode_with_thumbnails(*sizes: tuple[int, bytes]) -> str:
    lines = ["; generated by test"]
    for width, data in sizes:
        encoded = base64.b64encode(data).decode()
        lines.append(f"; thumbnail begin {width}x{width} {len(encoded)}")
        lines.extend(f"; {encoded[index : index + 60]}" for index in range(0, len(encoded), 60))
        lines.append("; thumbnail end")
    lines.append("G28")
    return "\n".join(lines)


def test_prefers_largest_thumbnail_at_or_below_300px(tmp_path):
    path = tmp_path / "multi.gcode"
    path.write_text(_gcode_with_thumbnails((300, b"large"), (48, b"icon")))
    assert library.extract_gcode_thumbnail(path) == b"large"


def test_skips_oversized_thumbnail_when_eligible_image_exists(tmp_path):
    path = tmp_path / "oversized.gcode"
    path.write_text(_gcode_with_thumbnails((301, b"oversized"), (96, b"eligible")))
    assert library.extract_gcode_thumbnail(path) == b"eligible"


def test_skips_malformed_larger_thumbnail_before_valid_smaller_one(tmp_path):
    valid = base64.b64encode(b"small-preview").decode()
    path = tmp_path / "malformed.gcode"
    path.write_text(
        "; thumbnail begin 300x300 4\n; @@@@\n; thumbnail end\n"
        f"; thumbnail begin 96x96 {len(valid)}\n; {valid}\n; thumbnail end\n"
    )
    assert library.extract_gcode_thumbnail(path) == b"small-preview"
